-- Sales Ledger: database schema + row level security (Supabase / Postgres).
-- Safe to commit: contains no passwords and no business data.
-- Run this FIRST in the Supabase SQL Editor, then 02_data.sql, then 03_users.sql.

create table if not exists public.branch_meta (
  br   text primary key,
  data jsonb not null            -- {name, dates[], adjSales, adjExp, wages[], wageSummary}
);

create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  username    text not null unique,
  name        text not null,
  role        text not null check (role in ('admin','manager')),
  br          text references public.branch_meta(br),
  must_change boolean not null default false,
  check ((role = 'admin' and br is null) or (role = 'manager' and br is not null))
);

create table if not exists public.cats (
  br      text not null references public.branch_meta(br),
  sec     text not null check (sec in ('sales','expense','cash','card','transfer','disc')),
  label   text not null,
  counted boolean not null default true,
  primary key (br, sec, label)
);

create table if not exists public.entries (
  id   bigint primary key,       -- generated by the app (millisecond clock based)
  br   text not null references public.branch_meta(br),
  date date not null,
  sec  text not null check (sec in ('sales','expense','cash','card','transfer','disc')),
  cat  text not null,
  amt  numeric(12,2) not null,
  ref  text not null default '',
  note text not null default '',
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid()
);
create index if not exists entries_br_date on public.entries (br, date);

-- helpers (security definer so policies can read profiles without recursion)
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as
$$ select coalesce((select role = 'admin' from public.profiles where id = auth.uid()), false) $$;

create or replace function public.my_branch() returns text
language sql stable security definer set search_path = public as
$$ select br from public.profiles where id = auth.uid() $$;

create or replace function public.clear_must_change() returns void
language sql security definer set search_path = public as
$$ update public.profiles set must_change = false where id = auth.uid() $$;

create or replace function public.touch() returns trigger language plpgsql as
$$ begin new.updated_at := now(); new.updated_by := auth.uid(); return new; end $$;
drop trigger if exists entries_touch on public.entries;
create trigger entries_touch before insert or update on public.entries
  for each row execute function public.touch();

-- row level security
alter table public.branch_meta enable row level security;
alter table public.profiles    enable row level security;
alter table public.cats        enable row level security;
alter table public.entries     enable row level security;

drop policy if exists meta_read   on public.branch_meta;
drop policy if exists meta_write  on public.branch_meta;
drop policy if exists prof_read   on public.profiles;
drop policy if exists cats_all    on public.cats;
drop policy if exists entries_all on public.entries;

create policy meta_read  on public.branch_meta for select to authenticated
  using (public.is_admin() or br = public.my_branch());
create policy meta_write on public.branch_meta for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
create policy prof_read  on public.profiles for select to authenticated
  using (id = auth.uid() or public.is_admin());
create policy cats_all   on public.cats for all to authenticated
  using (public.is_admin() or br = public.my_branch())
  with check (public.is_admin() or br = public.my_branch());
create policy entries_all on public.entries for all to authenticated
  using (public.is_admin() or br = public.my_branch())
  with check (public.is_admin() or br = public.my_branch());

-- privileges: nothing for anonymous visitors
revoke all on public.branch_meta, public.profiles, public.cats, public.entries from anon;
grant select, insert, update, delete on public.branch_meta, public.cats, public.entries to authenticated;
grant select on public.profiles to authenticated;
revoke execute on function public.clear_must_change() from public, anon;
grant  execute on function public.clear_must_change() to authenticated;
